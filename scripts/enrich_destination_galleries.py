def enrich_destinations() -> None:
    """Enrich destinations.json with additional verified media records."""
    with open(DESTINATIONS_FILE, "r", encoding="utf-8") as f:
        destinations = json.load(f)

    dest_by_slug = {d["slug"]: d for d in destinations}
    added_count = 0

    for slug, extra_items in ADDITIONAL_GALLERY_MEDIA.items():
        dest = dest_by_slug.get(slug)
        if not dest:
            print(f"Destination '{slug}' not found in catalogue, skipping.")
            continue

        existing_media = dest.get("media", [])
        existing_urls = {m.get("url") for m in existing_media}

        for item in extra_items:
            if item["url"] in existing_urls:
                continue

            media_id = f"media-{slug}-{item['suffix']}"
            new_media = {
                "id": media_id,
                "destination_id": dest["id"],
                "url": item["url"],
                "thumbnail_url": item["thumbnail_url"],
                "caption_en": item["caption_en"],
                "caption_kn": item.get("caption_kn"),
                "alt_en": item["alt_en"],
                "alt_kn": item.get("alt_kn"),
                "source_name": item["source_name"],
                "source_url": item["source_url"],
                "license_type": item["license_type"],
                "license_url": "https://creativecommons.org/licenses/by-sa/4.0",
                "attribution": item["attribution"],
                "is_primary": False,
                "verification_status": item.get("verification_status", "verified_authentic"),
                "media_type": "photograph",
            }
            existing_media.append(new_media)
            added_count += 1

        dest["media"] = existing_media

    with open(DESTINATIONS_FILE, "w", encoding="utf-8") as f:
        json.dump(destinations, f, indent=2, ensure_ascii=False)

    print(f"Enrichment complete! Added {added_count} verified gallery photographs.")


if __name__ == "__main__":
    enrich_destinations()
